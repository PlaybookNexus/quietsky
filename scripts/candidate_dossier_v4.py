# candidate_dossier_v4.py

from pathlib import Path
import pandas as pd

# =====================================================
# CONFIG
# =====================================================

BASE_DIR = Path(__file__).resolve().parent.parent

INPUT_FILE = (
    BASE_DIR /
    "quiet_sky_rankings_v4.csv"
)

OUTPUT_DIR = (
    BASE_DIR /
    "reviews"
)

TOP_N = 25

# =====================================================
# SETUP
# =====================================================

OUTPUT_DIR.mkdir(
    exist_ok=True
)

print()
print("=" * 60)
print("QUIET SKY DOSSIER GENERATOR V4")
print("=" * 60)

# =====================================================
# LOAD
# =====================================================

df = pd.read_csv(
    INPUT_FILE
)

df = df.head(TOP_N)

print()
print(
    f"Candidates : {len(df)}"
)

# =====================================================
# DOSSIERS
# =====================================================

for _, row in df.iterrows():

    rank = int(
        row["rank"]
    )

    target = str(
        row["name"]
    )

    filename = (

        target

        .replace("/", "_")
        .replace("\\", "_")
        .replace(":", "_")
        .replace("*", "_")
        .replace("?", "_")
        .replace('"', "_")
        .replace("<", "_")
        .replace(">", "_")
        .replace("|", "_")
        .replace(" ", "_")

    )

    filepath = (

        OUTPUT_DIR /

        f"{rank:03d}_{filename}.md"

    )

    composite = float(
        row["composite_score"]
    )

    optical = float(
        row["optical_score"]
    )

    infrared = float(
        row["infrared_score"]
    )

    tess = float(
        row["tess_score"]
    )

    percentile = float(
        row["tess_percentile"]
    )

    # -----------------------------------------
    # INTERPRETATION
    # -----------------------------------------

    observations = []

    if tess > 0:

        observations.append(
            "- Detected in TESS ranking dataset."
        )

    if percentile >= 99:

        observations.append(
            "- Ranked within the top 1% of TESS anomalies."
        )

    elif percentile >= 95:

        observations.append(
            "- Ranked within the top 5% of TESS anomalies."
        )

    elif percentile >= 90:

        observations.append(
            "- Ranked within the top 10% of TESS anomalies."
        )

    if optical > infrared:

        observations.append(
            "- Optical measurements contribute more strongly than infrared measurements."
        )

    elif infrared > optical:

        observations.append(
            "- Infrared measurements contribute more strongly than optical measurements."
        )

    else:

        observations.append(
            "- Optical and infrared measurements contribute similarly."
        )

    # -----------------------------------------
    # RECOMMENDATION
    # -----------------------------------------

    if rank <= 10:

        recommendation = (
            "Highest priority follow-up target."
        )

    elif rank <= 25:

        recommendation = (
            "Recommended for additional investigation."
        )

    else:

        recommendation = (
            "Monitor for future review."
        )

    # -----------------------------------------
    # DOSSIER
    # -----------------------------------------

    lines = [

        f"# Quiet Sky Candidate Dossier",

        "",

        f"## {target}",

        "",

        f"Composite Rank: {rank}",

        f"Composite Score: {composite:.6f}",

        "",

        "---",

        "",

        "## Scoring Summary",

        "",

        f"- Optical Score: {optical:.6f}",

        f"- Infrared Score: {infrared:.6f}",

        f"- TESS Score: {tess:.6f}",

        f"- TESS Percentile: {percentile:.2f}",

        "",

        "---",

        "",

        "## Observations",

        ""

    ]

    lines.extend(
        observations
    )

    lines.extend([

        "",

        "---",

        "",

        "## Analyst Recommendation",

        "",

        recommendation,

        "",

        "---",

        "",

        "## Suggested Follow-Up",

        "",

        "- Review historical survey imagery",

        "- Review TESS light curves",

        "- Compare against category peers",

        "- Examine multi-wavelength consistency",

        "- Reassess after future catalog updates",

        "",

        "---",

        "",

        "Generated by Quiet Sky v4"

    ])

    with open(
        filepath,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(
            "\n".join(lines)
        )

# =====================================================
# SUMMARY
# =====================================================

print()
print("=" * 60)
print("DOSSIERS CREATED")
print("=" * 60)

print()

print(
    f"Candidates Processed : "
    f"{len(df)}"
)

print(
    f"Output Folder : "
    f"{OUTPUT_DIR}"
)

print()